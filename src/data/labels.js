export const LABELS = Object.fromEntries(
  RAW.trim().split('\n').map((line) => {
    const i = line.indexOf('=');
    return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
  }),
);

// Etiquetas que dependen de la acción (el mismo nombre técnico significa cosas distintas).
const CONTEXT = [
  [/^\/agents\//, { id: 'Agente', idOrEmail: 'Agente' }],
  [/^\/channels\//, { id: 'Canal' }],
  [/^\/constants\//, { id: 'Dato fijo' }],
  [/^\/attention-queues/, { id: 'Cola de atención' }],
  [/^\/webhooks\/\{id\}/, { id: 'Webhook' }],
  [/^\/intents\//, { idOrName: 'Respuesta del bot' }],
  [/^\/roles\//, { idOrName: 'Rol' }],
  [/^\/whatsapp\/templates\//, { idOrName: 'Plantilla' }],
  [/\/stores\/\{code\}/, { code: 'Sucursal' }],
  [/^\/agents$/, { emails: 'Buscar por correo' }],
  [/^\/chats$/, { emails: 'Correo del cliente', name: 'Nombre del cliente' }],
];

export function labelFor(name, path = '') {
  for (const [re, map] of CONTEXT) {
    if (re.test(path) && map[name]) return map[name];
  }
  if (LABELS[name]) return LABELS[name];
  return humanize(name);
}

// "someFieldName" / "some-field_name" → "Some field name"
export function humanize(name) {
  const words = String(name)
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/[-_.]+/g, ' ')
    .trim()
    .toLowerCase();
  return words.charAt(0).toUpperCase() + words.slice(1);
}
